def clean_txt(text: str) -> str:
    """Safely strip out non-Latin-1 characters to prevent FPDFUnicodeEncodingException."""
    if not text:
        return ""
    # Emojis/Icons mapping or deletion
    text = text.replace('🚨', '').replace('🤖', '').replace('⚙️', '').replace('📄', '')
    # Typographic replacements
    text = text.replace('’', "'").replace('“', '"').replace('”', '"').replace('—', '-').replace('–', '-')
    text = text.replace('**', '').replace('__', '')
    # Strict encoding conversion
    return text.encode('latin-1', 'ignore').decode('latin-1')

class ReportPDF(FPDF):
    def header(self):
        self.set_font('helvetica', 'B', 16)
        self.cell(0, 10, 'ISCOR AI - Screening Report', border=False, ln=True, align='L')
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font('helvetica', 'I', 8)
        self.cell(0, 10, f'Page {self.page_no()}', 0, 0, 'C')
        
    def add_section(self, title: str, content: str):
        self.set_font('helvetica', 'B', 12)
        self.set_text_color(43, 36, 56) # ISCOR ink color
        self.cell(0, 10, clean_txt(title), ln=True)
        self.set_font('helvetica', '', 11)
        self.set_text_color(50, 50, 50)
        self.multi_cell(0, 6, clean_txt(content))
        self.ln(5)


def generate_pdf_report(report_data: Dict[str, Any]) -> bytes:
    """
    Generates a PDF from the screening report data and returns the raw bytes.
    """
    pdf = ReportPDF()
    pdf.add_page()
    
    # Risk Level & Probabilities
    risk_label = report_data.get('risk_label', 'Unknown')
    probs = report_data.get('risk_probabilities', {})
    conf = probs.get(risk_label, 0.0)
    
    pdf.set_font('helvetica', 'B', 14)
    pdf.set_text_color(227, 168, 87) # amber color
    pdf.cell(0, 10, f"Risk Level: {clean_txt(risk_label)} ({conf:.0%} confidence)", ln=True)
    pdf.set_font('helvetica', '', 10)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(0, 6, f"Probabilities: Low {probs.get('Low',0):.0%} | Moderate {probs.get('Moderate',0):.0%} | High {probs.get('High',0):.0%}", ln=True)
    pdf.ln(5)
    
    # Top Factors
    factors = report_data.get('top_factors', [])
    if factors:
        pdf.set_font('helvetica', 'B', 12)
        pdf.set_text_color(43, 36, 56)
        pdf.cell(0, 10, "Top Driving Factors", ln=True)
        pdf.set_font('helvetica', '', 11)
        for f in factors:
            name = f['feature'].replace('_', ' ')
            direction = f['direction']
            val = f['shap_value']
            pct = f.get('cohort_percentile', 50)
            cf = f.get('counterfactual', '')
            
            icon = "(+)" if direction == "increases_risk" else "(-)"
            pdf.set_text_color(50, 50, 50)
            pdf.cell(0, 6, f"{icon} {clean_txt(name)} (Higher than {pct}% of similar students)", ln=True)
            if cf:
                pdf.set_text_color(120, 120, 120)
                pdf.cell(5) # indent
                pdf.multi_cell(0, 5, clean_txt(cf))
        pdf.ln(5)
        
    # Content sections
    if report_data.get('explanation'):
        pdf.add_section("Explanation", report_data['explanation'])
        
    if report_data.get('wellness_suggestions'):
        pdf.add_section("Wellness Suggestions", report_data['wellness_suggestions'])
        
    if report_data.get('weekly_plan'):
        pdf.add_section("Weekly Plan", report_data['weekly_plan'])
        
    if report_data.get('crisis_mode'):
        pdf.set_font('helvetica', 'B', 11)
        pdf.set_text_color(200, 50, 50)
        pdf.cell(0, 10, "Safety Check: Please refer to the crisis resources provided.", ln=True)
        
    # Notice
    pdf.ln(10)
    pdf.set_font('helvetica', 'I', 9)
    pdf.set_text_color(150, 150, 150)
    pdf.multi_cell(0, 5, "Notice: This report is generated by ISCOR AI, an educational screening tool. It is not a clinical diagnosis and cannot replace professional medical advice.")
    
    # Output to bytes
    return bytes(pdf.output())
